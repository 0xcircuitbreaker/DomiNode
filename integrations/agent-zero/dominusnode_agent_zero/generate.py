"""Regenerate the Agent Zero tool classes and prompt files from the core tool specs.

Output (relative to the integration root, mirroring an Agent Zero checkout):

- ``python/tools/dominusnode_<tool>.py``: ``Tool`` subclasses
- ``prompts/agent.system.tool.dominusnode_<tool>.md``: per-tool usage prompt
- ``prompts/agent.system.tools.dominusnode.md``: index that includes them all

Run ``python -m dominusnode_agent_zero.generate`` after editing ``_core.py``.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict

from dominusnode_agent_zero._core import PREFIX, TOOL_SPECS

ROOT = Path(__file__).resolve().parent.parent
TOOLS_DIR = ROOT / "python" / "tools"
PROMPTS_DIR = ROOT / "prompts"


def _class_name(name: str) -> str:
    return "DominusNode" + "".join(w.capitalize() for w in name.split("_"))


def _example(spec: Dict[str, Any]) -> Dict[str, Any]:
    ex: Dict[str, Any] = {}
    for p, s in spec["parameters"]["properties"].items():
        if p not in spec["parameters"]["required"]:
            continue
        if "enum" in s:
            ex[p] = s["enum"][0]
        elif s["type"] == "integer":
            ex[p] = s.get("minimum", 1)
        elif p == "url":
            ex[p] = "https://example.com"
        elif p == "amount_musd":
            ex[p] = "1000000"
        else:
            ex[p] = f"<{p}>"
    return ex


def render_tool(spec: Dict[str, Any]) -> str:
    name = PREFIX + spec["name"]
    return (
        f'"""Agent Zero tool: {name} (generated by dominusnode_agent_zero.generate)."""\n\n'
        "from python.helpers.tool import Response, Tool\n\n"
        "from dominusnode_agent_zero.runtime import execute\n\n\n"
        f"class {_class_name(spec['name'])}(Tool):\n"
        "    async def execute(self, **kwargs) -> Response:\n"
        f'        result = await execute("{spec["name"]}", kwargs)\n'
        "        return Response(message=result, break_loop=False)\n"
    )


def render_prompt(spec: Dict[str, Any]) -> str:
    name = PREFIX + spec["name"]
    props = spec["parameters"]["properties"]
    req = spec["parameters"]["required"]
    lines = [f"### {name}", spec["description"], ""]
    if props:
        lines.append("args:")
        for p, s in props.items():
            extra = f" one of: {', '.join(map(str, s['enum']))}." if "enum" in s else ""
            lines.append(f"- {p} ({s['type']}, {'required' if p in req else 'optional'}): {s['description']}{extra}")
    else:
        lines.append("args: none")
    call = {"thoughts": [f"I should use {name}."], "headline": spec["description"].split(".")[0][:80],
            "tool_name": name, "tool_args": _example(spec)}
    lines += ["usage:", "~~~json", json.dumps(call, indent=4), "~~~", ""]
    return "\n".join(lines)


def render_index() -> str:
    head = [
        "## DominusNode relay network tools",
        "Fetch the public web through exit IPs contributed by other agents, pay per GB (live prices from",
        "dominusnode_network_pricing), and earn by contributing your own IP with the node agent",
        "(dominusnode_node_setup_guide). The API key is configured in the environment; never ask for it.",
        "",
    ]
    return "\n".join(head + [f"{{{{ include './agent.system.tool.{PREFIX}{s['name']}.md' }}}}" for s in TOOL_SPECS]) + "\n"


def render_all() -> Dict[Path, str]:
    out: Dict[Path, str] = {}
    for s in TOOL_SPECS:
        out[TOOLS_DIR / f"{PREFIX}{s['name']}.py"] = render_tool(s)
        out[PROMPTS_DIR / f"agent.system.tool.{PREFIX}{s['name']}.md"] = render_prompt(s)
    out[PROMPTS_DIR / f"agent.system.tools.{PREFIX.rstrip('_')}.md"] = render_index()
    return out


def main() -> None:
    for d, pat in ((TOOLS_DIR, PREFIX + "*.py"), (PROMPTS_DIR, "agent.system.tool*.dominusnode*.md")):
        d.mkdir(parents=True, exist_ok=True)
        for f in d.glob(pat):
            f.unlink()
    for path, text in render_all().items():
        path.write_text(text)


if __name__ == "__main__":
    main()
