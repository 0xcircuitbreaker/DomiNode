"""Regenerate ``plugins/*.yaml`` + ``plugins/*.py`` from the core tool specs.

Run ``python -m dominusnode_taskweaver.generate_plugins`` after editing ``_core.py``.
The tests check that the committed files match this output.
"""

from __future__ import annotations

from pathlib import Path
from typing import Dict, List

import yaml

from dominusnode_taskweaver._core import PREFIX, TOOL_SPECS

PLUGIN_DIR = Path(__file__).parent / "plugins"
_TW_TYPES = {"string": "str", "integer": "int", "boolean": "bool"}


def _class_name(name: str) -> str:
    return "DominusNode" + "".join(w.capitalize() for w in name.split("_"))


def _py_arg(p: str) -> str:
    return "from_" if p == "from" else p


def render(spec: Dict) -> Dict[str, str]:
    name = PREFIX + spec["name"]
    props = spec["parameters"]["properties"]
    required: List[str] = spec["parameters"]["required"]
    desc = spec["description"]
    for p, s in props.items():
        if "enum" in s:
            props[p] = dict(s, description=f"{s['description']} One of: {', '.join(map(str, s['enum']))}.")
    doc = {
        "name": name,
        "enabled": True,
        "required": False,
        "description": desc,
        "parameters": [
            {"name": _py_arg(p), "type": _TW_TYPES[s["type"]], "required": p in required, "description": s["description"]}
            for p, s in props.items()
        ],
        "returns": [{"name": "result", "type": "str",
                     "description": "JSON string with the result, or {\"error\": ...} (credentials scrubbed)."}],
        "configurations": {"base_url": "", "proxy_host": ""},
    }
    ordered = [p for p in props if p in required] + [p for p in props if p not in required]
    sig = ", ".join(["self"] + [_py_arg(p) if p in required else f"{_py_arg(p)}=None" for p in ordered])
    kwargs = ", ".join(f'"{p}": {_py_arg(p)}' for p in props)
    py = (
        f'"""TaskWeaver plugin: {name} (generated by dominusnode_taskweaver.generate_plugins)."""\n\n'
        "from taskweaver.plugin import Plugin, register_plugin\n\n"
        "from dominusnode_taskweaver.runtime import run\n\n\n"
        "@register_plugin\n"
        f"class {_class_name(spec['name'])}(Plugin):\n"
        f"    def __call__({sig}) -> str:\n"
        f'        return run(self, "{spec["name"]}", {{{kwargs}}})\n'
    )
    return {f"{name}.yaml": yaml.safe_dump(doc, sort_keys=False, width=110), f"{name}.py": py}


def render_all() -> Dict[str, str]:
    out: Dict[str, str] = {}
    for spec in TOOL_SPECS:
        out.update(render({**spec, "parameters": {**spec["parameters"],
                                                  "properties": dict(spec["parameters"]["properties"])}}))
    return out


def main() -> None:
    PLUGIN_DIR.mkdir(exist_ok=True)
    for f in PLUGIN_DIR.glob(PREFIX + "*"):
        f.unlink()
    for fname, text in render_all().items():
        (PLUGIN_DIR / fname).write_text(text)


if __name__ == "__main__":
    main()
