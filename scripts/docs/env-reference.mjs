#!/usr/bin/env node
// Generate docs/agent-network/ENV_REFERENCE.md from the environment variables
// the server-side packages actually read (process.env.X, process.env["X"],
// env["X"] on an injected env object). Test files and build output are skipped.
//
//   node scripts/docs/env-reference.mjs           # rewrite the file
//   node scripts/docs/env-reference.mjs --check   # exit 1 if it is stale (CI)
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUT = join(root, "docs", "agent-network", "ENV_REFERENCE.md");
const PACKAGES = ["shared", "proxy-gateway", "dashboard", "billing", "metering", "node-agent"];

// Names that match the pattern but are not configuration.
const IGNORE = new Set(["NODE_ENV_TEST"]);

const READ_RE = /\b(?:process\.env|env)(?:\[\s*["']([A-Z][A-Z0-9_]+)["']\s*\]|\.([A-Z][A-Z0-9_]+))/g;
// Default right after the read: ?? "x" / || "x" / ?? 123
const DEFAULT_RE = /^\s*(?:\?\?|\|\|)\s*(?:"([^"\n]{0,80})"|'([^'\n]{0,80})'|(-?\d[\d_]*))/;

function walk(dir, out) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) {
      if (name === "node_modules" || name === "dist") continue;
      walk(p, out);
    } else if (/\.(ts|mts|js|mjs)$/.test(name) && !/\.test\.|\.spec\.|\.d\.ts$/.test(name)) {
      out.push(p);
    }
  }
  return out;
}

function collect(pkg) {
  const src = join(root, "packages", pkg, "src");
  if (!existsSync(src)) return new Map();
  const vars = new Map(); // name -> { files:Set, defaults:Set }
  for (const file of walk(src, []).sort()) {
    const text = readFileSync(file, "utf8");
    for (const m of text.matchAll(READ_RE)) {
      const name = m[1] ?? m[2];
      if (!name || IGNORE.has(name)) continue;
      const v = vars.get(name) ?? { files: new Set(), defaults: new Set() };
      v.files.add(relative(join(root, "packages", pkg), file).replace(/\\/g, "/"));
      const d = DEFAULT_RE.exec(text.slice(m.index + m[0].length));
      if (d) {
        const val = d[1] ?? d[2] ?? d[3];
        if (val !== undefined) v.defaults.add(val === "" ? '""' : val);
      }
      vars.set(name, v);
    }
  }
  return vars;
}

const SELFHOST_VARS = [
  ["CLOUDFLARE_TUNNEL_TOKEN_FILE", "./selfhost/cloudflared.token", "cloudflared (TLS_MODE=cloudflare); path of a 0600 file, the token is never in .env"],
  ["COORD_ADDITIONAL_PUBKEYS", "", "api federation document (ROLE=coordinator: gateway VPS key)"],
  ["COORD_PUBKEY", "", "installer pin of the coordinator key (ROLE=gateway)"],
  ["DB_WG_BIND", "", "Postgres publish address on the WireGuard interface (ROLE=coordinator)"],
  ["GATEWAY_DATABASE_URL", "", "gateway DATABASE_URL over WireGuard (ROLE=gateway)"],
  ["GATEWAY_PUBKEY", "", "gateway VPS public key (ROLE=coordinator)"],
  ["PROXY_HOST", "", "advertised proxy hostname"],
  ["RELAY_HOST", "", "advertised relay and node tunnel hostname"],
  ["ROLE", "all", "all, coordinator or gateway"],
  ["TLS_MODE", "auto", "auto, internal, off or cloudflare"],
];

function render() {
  const lines = [
    "# Environment variable reference",
    "",
    "Generated by `node scripts/docs/env-reference.mjs` from the `process.env` reads in",
    "each server-side package (test files excluded). Do not edit by hand: CI runs",
    "`npm run docs:env:check` and fails when this file is stale.",
    "",
    "Defaults are the literal fallbacks found next to the read (`?? \"x\"`); a blank",
    "default means the code has no inline fallback (unset, computed, or validated",
    "elsewhere). Meaning and required/optional status are documented in",
    "[DEPLOYMENT.md](DEPLOYMENT.md).",
    "",
  ];
  for (const pkg of PACKAGES) {
    const vars = collect(pkg);
    if (vars.size === 0) continue;
    lines.push(`## ${pkg}`, "", "| Variable | Default(s) | Read in |", "|---|---|---|");
    for (const name of [...vars.keys()].sort()) {
      const v = vars.get(name);
      const defs = [...v.defaults].sort().map((d) => `\`${d.replace(/\|/g, "\\|")}\``).join(", ");
      const files = [...v.files].sort().map((f) => `\`${f}\``).join(", ");
      lines.push(`| \`${name}\` | ${defs} | ${files} |`);
    }
    lines.push("");
  }
  lines.push(
    "## Self-host installer (`.env`, read by compose and `scripts/selfhost/install.sh`)",
    "",
    "Not scanned from code; maintained in `SELFHOST_VARS` in the generator. See DEPLOYMENT.md self-host section.",
    "",
    "| Variable | Default(s) | Used by |",
    "|---|---|---|",
    ...SELFHOST_VARS.map(([n, d, u]) => `| \`${n}\` | ${d ? `\`${d}\`` : ""} | ${u} |`),
    "",
  );
  return lines.join("\n");
}

const next = render();
if (process.argv.includes("--check")) {
  const cur = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (cur !== next) {
    console.error("docs/agent-network/ENV_REFERENCE.md is stale. Run: npm run docs:env");
    process.exit(1);
  }
  console.log("ENV_REFERENCE.md is current");
} else {
  writeFileSync(OUT, next);
  console.log(`wrote ${relative(root, OUT)}`);
}
