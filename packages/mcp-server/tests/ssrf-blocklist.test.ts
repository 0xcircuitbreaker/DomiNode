import { describe, it, expect } from "vitest";
import { isPrivateIp } from "../src/proxy-fetch.js";

describe("isPrivateIp (CIDR BlockList)", () => {
  it.each([
    "127.0.0.1", "10.1.2.3", "172.31.255.255", "192.168.1.1", "100.64.0.1", "169.254.169.254",
    "192.0.0.8", "198.18.0.1", "198.19.255.255", "0.0.0.0", "224.0.0.1", "255.255.255.255",
    "0x7f000001", "2130706433", "0177.0.0.1",
    "::1", "::", "fe80::1", "febf::1", "fec0::1", "feff::1", "fc00::1", "fd12::1", "ff02::1",
    "::ffff:127.0.0.1", "::ffff:7f00:1", "::127.0.0.1", "::a00:1",
    "64:ff9b::10.0.0.1", "64:ff9b::7f00:1", "64:ff9b::c0a8:101",
    "2001:0:4136:e378::1", "2002:7f00:1::1", "[::1]", "fe80::1%25eth0",
  ])("blocks %s", (ip) => {
    expect(isPrivateIp(ip)).toBe(true);
  });

  it.each([
    "93.184.216.34", "8.8.8.8", "172.32.0.1", "198.20.0.1", "100.128.0.1", "192.0.1.1",
    "2606:4700::1111", "::ffff:93.184.216.34", "64:ff9b::8.8.8.8", "fe7f::1", "example.com",
  ])("allows %s", (ip) => {
    expect(isPrivateIp(ip)).toBe(false);
  });
});
