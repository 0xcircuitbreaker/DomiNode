#!/usr/bin/env node
// Generate src/coord-pins.generated.ts from DN_COORD_PUBKEYS (comma-separated
// raw ed25519 public keys, 64 lowercase hex chars each; see
// scripts/gen-coord-key.sh). Dev builds leave the list empty. Release builds
// run with --require so a missing/invalid pin list fails the build.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = process.argv.includes("--require");
const raw = (process.env.DN_COORD_PUBKEYS ?? "").trim();
const pins = [...new Set(raw.split(",").map((p) => p.trim().toLowerCase()).filter(Boolean))];
for (const p of pins) {
  if (!/^[0-9a-f]{64}$/.test(p)) {
    console.error(`gen-coord-pins: invalid pin (expected 64 hex chars): ${p.slice(0, 80)}`);
    process.exit(1);
  }
}
if (pins.length > 16) { console.error("gen-coord-pins: too many pins (max 16)"); process.exit(1); }
if (require && pins.length === 0) { console.error("gen-coord-pins: DN_COORD_PUBKEYS is required for release builds"); process.exit(1); }

const outIdx = process.argv.indexOf("--out");
const out = outIdx > 0 && process.argv[outIdx + 1]
  ? process.argv[outIdx + 1]
  : join(dirname(fileURLToPath(import.meta.url)), "..", "src", "coord-pins.generated.ts");
const body = `// GENERATED by scripts/gen-coord-pins.mjs from DN_COORD_PUBKEYS. Do not edit.
// The committed copy is the empty dev list; release builds regenerate it.
export const GENERATED_COORD_PUBKEYS: readonly string[] = ${JSON.stringify(pins)};
`;
writeFileSync(out, body);
console.log(`gen-coord-pins: ${pins.length} pin(s) embedded`);
